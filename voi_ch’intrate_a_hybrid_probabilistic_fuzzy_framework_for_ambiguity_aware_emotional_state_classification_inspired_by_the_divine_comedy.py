manifest_df["llr_intensity"] = scores.apply(lambda x: x[1])

# Winsorization ringan biar outlier tidak merusak fuzzy scale
low = manifest_df["llr_signed"].quantile(0.01)
high = manifest_df["llr_signed"].quantile(0.99)

