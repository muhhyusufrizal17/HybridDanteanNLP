import skfuzzy as fuzz
def build_67_nonoverlap_trapezoids(n_slots=67, eps_ratio=0.15):
    w = 1.0 / n_slots
    eps = eps_ratio * w
    traps = {}
    for k in range(n_slots):
        a = k * w
        d = (k + 1) * w
        b = a + eps
        c = d - eps
        traps[k + 1] = [a, b, c, d]
    return traps
